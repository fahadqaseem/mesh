"""Regenerate docs/results/2026-11-09_v3_gaussians.md: v3 headline (TSDF default) and Gaussian centres vs points.

Usage: python scripts/v3_report.py [--out docs/results/2026-11-09_v3_gaussians.md]
Safe on partial results. Everything from "<!-- manual -->" onwards in the existing doc is kept.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import numpy as np

from robustness_report import (DEV, MANUAL, MESH_COLS, OUT, SET_A, SET_B, STAT_COLS, cells, collect, header, line, load,
                               pipe, sd, value)

SEEDS = [42, 7, 123]
INPUTS = [("filtered points (v2, previous default)", "_tex_8v"), ("TSDF points (v3, new default)", "_tex_v3"),
          ("Gaussian centres (3DGS, msplat)", "_gs")]


def mesh_seed(run: str, seed: int) -> dict | None:
    return load(OUT / run / "mesh" / f"meshflow_s{seed}.json")


def seed_mean(shape: str, suffix: str) -> dict:
    """Mesh metrics averaged over the 3 seeds (only if all 3 exist)."""
    ms = [mesh_seed(shape + suffix, s) for s in SEEDS]
    if not all(ms):
        return {"mesh": None}
    return {"mesh": {k: float(np.mean([m[k] for m in ms])) for k, _, _ in MESH_COLS}}


def paired(shapes: list[str], a: str, b: str, key: str) -> str:
    d = [value(pipe(s, b), "mesh", key) - value(pipe(s, a), "mesh", key) for s in shapes
         if value(pipe(s, a), "mesh", key) is not None and value(pipe(s, b), "mesh", key) is not None]
    if not d:
        return "-"
    d = np.array(d)
    better = (d < 0).sum() if key in ("CD", "HD") else (d > 0).sum()
    return f"{d.mean():+.3g} ± {sd(d):.2g} (better on {better} of {len(d)})"


def queue_line(name: str) -> str:
    q, st = OUT / f"v3_queue_{name}" / "queue.tsv", OUT / f"v3_queue_{name}" / "status.tsv"
    if not q.exists():
        return ""
    total = sum(1 for _ in q.open())
    last = {}
    for r in (ln.rstrip("\n").split("\t") for ln in st.open()) if st.exists() else []:
        if len(r) >= 4:
            last[r[2]] = r[3]
    bad = sorted(k for k, v in last.items() if v != "ok")
    return f"Queue {name}: {sum(v == 'ok' for v in last.values())} of {total} jobs ok" + \
        (f"; not ok: {', '.join(bad)}" if bad else "") + "."


def fig_inputs(path: Path) -> bool:
    if not any(pipe(s, "_gs")["mesh"] for s in SET_A + SET_B):
        return False
    from robustness_report import BLUE, ORANGE, SURFACE, dot, plot_style
    plt = plot_style()
    rows = INPUTS + [("upper bound: clean GT points", "_gtsamples")]
    metrics = [("CD", "mesh Chamfer (lower is better)"), ("F1@0.02", "mesh F1@0.02 (higher is better)"), ("V", "mesh vertices")]
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 2.9), sharey=True)
    y = np.arange(len(rows))[::-1].astype(float)
    for ax, (mkey, xlabel) in zip(axes, metrics):
        for shapes, color, off in [(SET_A, BLUE, 0.13), (SET_B, ORANGE, -0.13)]:
            for yi, (_, suf) in zip(y, rows):
                vals = collect([pipe(s, suf) for s in shapes], "mesh", mkey)
                if len(vals):
                    ax.plot([vals.mean() - sd(vals), vals.mean() + sd(vals)], [yi + off] * 2, color=color, lw=1.2,
                            alpha=0.55, zorder=2)
                    dot(ax, [vals.mean()], [yi + off], color, size=6.5)
        ax.set_xlabel(xlabel)
        ax.grid(axis="y", visible=False)
    axes[0].set_yticks(y, [n for n, _ in rows])
    handles = [plt.Line2D([], [], color=BLUE, lw=1.2, marker="o", ms=6.5, mec=SURFACE, label="set A (7 shapes)"),
               plt.Line2D([], [], color=ORANGE, lw=1.2, marker="o", ms=6.5, mec=SURFACE,
                          label="set B (12 shapes, clean test set)")]
    fig.legend(handles=handles, loc="upper center", ncol=2, bbox_to_anchor=(0.6, 1.0), fontsize=8)
    fig.text(0.01, 0.97, "MeshFlow input: mean ± std over shapes, seed 42", color="#52514e", fontsize=8, va="top")
    fig.tight_layout(rect=(0, 0, 1, 0.9))
    fig.savefig(path, dpi=170)
    plt.close(fig)
    return True


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/results/2026-11-09_v3_gaussians.md")
    out = Path(ap.parse_args().out)
    manual = out.read_text()[out.read_text().index(MANUAL):] if out.exists() and MANUAL in out.read_text() else ""
    lines = ["# Points stage v3 (TSDF default) and Gaussian centres as MeshFlow input", "",
             "Fahad Qaseem Khawar, 9 Nov 2026. Tables and figures regenerated by `scripts/v3_report.py`; the interpretation "
             "at the end is written by hand. Protocol v1 (`docs/eval_protocol.md`). Set A = 7 original shapes, set B = 12 "
             "new shapes (clean test set); pencilpot is the dev shape and is in no mean.", "",
             queue_line("headline"), queue_line("gaussians"), ""]

    lines += ["## 1. Headline with the new default points stage (TSDF fusion)", "",
              "Same 8 VGGT views and known focal; the v3 points stage fuses the depth maps in a TSDF "
              "(`configs/default.yaml` points.tsdf) instead of concatenating filtered per-view points. MeshFlow seed 42; "
              "v2 = the previous default, kept as the comparison row (its numbers are from 7 Nov).", ""]
    for name, shapes in [("Set B (12 shapes, clean test set)", SET_B), ("Set A (7 shapes)", SET_A)]:
        n = len(shapes)
        lines += [f"**{name}**", "", header(["stage"], MESH_COLS)]
        for label, suf in [("pipeline mesh, v3 TSDF points", "_tex_v3"), ("pipeline mesh, v2 filtered points", "_tex_8v"),
                           ("upper bound: clean GT points", "_gtsamples")]:
            lines.append(line([label] + cells([pipe(s, suf) for s in shapes], MESH_COLS, "mesh", n)))
        lines += ["", f"Paired per shape, v3 minus v2: Chamfer {paired(shapes, '_tex_8v', '_tex_v3', 'CD')}; F1@0.02 "
                      f"{paired(shapes, '_tex_8v', '_tex_v3', 'F1@0.02')}.", ""]
    n = len(SET_A)
    lines += ["**Set A, mean of 3 MeshFlow seeds (42, 7, 123)**", "", header(["stage"], MESH_COLS),
              line(["v3 TSDF points"] + cells([seed_mean(s, "_tex_v3") for s in SET_A], MESH_COLS, "mesh", n)),
              line(["v2 filtered points"] + cells([seed_mean(s, "_tex_8v") for s in SET_A], MESH_COLS, "mesh", n)), ""]
    d = pipe(DEV, "_tex_v3")
    if d["mesh"]:
        lines += [f"Dev pencilpot (not in means), v3: Chamfer {d['mesh']['CD']:.2f}, F1@0.02 {d['mesh']['F1@0.02']:.3f}, "
                  f"#V {d['mesh']['V']} (v2: 10.25, 0.305, 918).", ""]

    if any(pipe(s, "_gs")["points"] for s in [DEV] + SET_A + SET_B):
        pcols = [("CD", "points Chamfer", 2), ("F1@0.02", "points F1@0.02", 3)]
        lines += ["## 2. Gaussian centres vs TSDF points vs filtered points (MeshFlow input)", "",
                  "Gaussian centres: 3D Gaussian splatting trained on the 8 views with msplat (Metal, on the Mac), in VGGT's "
                  "frame with VGGT's cameras (known focal), initialised from 20k points of the v3 cloud, white background; "
                  "the centres of Gaussians with opacity >= 0.5 and largest axis <= 5% of the object are the points "
                  "(settings chosen on pencilpot only). All three inputs come from the same VGGT pass. MeshFlow seed 42.", ""]
        for name, shapes in [("Set B (12 shapes, clean test set)", SET_B), ("Set A (7 shapes)", SET_A)]:
            n = len(shapes)
            lines += [f"**{name}: points**", "", header(["input"], STAT_COLS + pcols)]
            for label, suf in INPUTS:
                runs = [pipe(s, suf) for s in shapes]
                lines.append(line([label] + cells(runs, STAT_COLS, "stats", n) + cells(runs, pcols, "points", n)))
            lines += ["", f"**{name}: meshes**", "", header(["input"], MESH_COLS)]
            for label, suf in INPUTS + [("upper bound: clean GT points", "_gtsamples")]:
                lines.append(line([label] + cells([pipe(s, suf) for s in shapes], MESH_COLS, "mesh", n)))
            lines += ["", f"Paired per shape, Gaussian centres minus TSDF points: Chamfer "
                          f"{paired(shapes, '_tex_v3', '_gs', 'CD')}; F1@0.02 {paired(shapes, '_tex_v3', '_gs', 'F1@0.02')}. "
                          f"Gaussian centres minus filtered points: Chamfer {paired(shapes, '_tex_8v', '_gs', 'CD')}.", ""]
        gi = [load(OUT / f"{s}_gs" / "points" / "gaussians.json") for s in SET_A + SET_B]
        gi = [g for g in gi if g]
        if gi:
            lines += [f"Training (msplat, {gi[0]['iters']} iterations, M4 Pro): "
                      f"{np.mean([g['train_s'] for g in gi]):.0f} ± {sd(np.array([g['train_s'] for g in gi])):.0f} s per "
                      f"object, {np.mean([g['gaussians'] for g in gi]):,.0f} Gaussians, "
                      f"{np.mean([g['kept'] for g in gi]):,.0f} centres kept, peak memory "
                      f"{max(g['peak_rss_gb'] for g in gi):.1f} GB (n={len(gi)}).", ""]
        p = Path("docs/results/figures/2026-11-09_inputs.png")
        if fig_inputs(p):
            lines += [f"![MeshFlow inputs]({os.path.relpath(p, out.parent)})", ""]
        lines += ["**Per shape (mesh Chamfer / F1@0.02)**", "", "| shape | filtered | TSDF | Gaussian centres |",
                  "|---|---:|---:|---:|"]
        for s in [DEV] + SET_A + SET_B:
            items = []
            for _, suf in INPUTS:
                m = pipe(s, suf)["mesh"]
                items.append(f"{m['CD']:.2f} / {m['F1@0.02']:.2f}" if m else "")
            if items[2]:
                lines.append(line([s + (" (dev)" if s == DEV else " (B)" if s in SET_B else "")] + items))
        lines.append("")
    text = "\n".join(lines) + "\n" + (manual or f"{MANUAL}\n## Interpretation\n\n(written when the queues have finished)\n")
    out.write_text(text)
    print(f"[report] {out}")


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(Path(__file__).parent))
    main()
