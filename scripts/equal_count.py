"""Equal-count comparison: TSDF vs TSDF + gap fill, both subsampled to exactly 1,000,000 points, protocol v1 + outliers.

Usage: python scripts/equal_count.py [--n 1000000] [--seed 0] [--out docs/results/2026-11-17_equal_count.md]
For each shape (dev + set A + set B) and each cloud (<s>_dense: 1M TSDF points; <s>_dfill: dense gap fill, 1.01M to
1.33M points), draws exactly n points uniformly at random without replacement (numpy default_rng(seed)), scores them with
protocol v1 (src/photo2mesh/eval/protocol.py score_points) and adds an outlier metric: the share of points whose exact
distance to the GT surface (Open3D RaycastingScene.compute_distance on the triangle mesh, in protocol v1's normalised
frame where the GT's largest extent is 1) exceeds 0.01 and 0.02. Writes outputs/<run>/eval/equal_count.json and the report.
CPU only, about 10 s per cloud.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from photo2mesh.eval.protocol import score_points, unit_cube_transform
from photo2mesh.io import load_mesh, load_points_ply

sys.path.insert(0, str(Path(__file__).parent))
from make_points_queue import DEV, SET_A, SET_B  # noqa: E402

RUNS = [("TSDF (1M)", "_dense"), ("TSDF + gap fill (subsampled to 1M)", "_dfill")]
COLS = [("CD", "Chamfer", 2), ("HD", "Hausdorff", 1), ("F1@0.01", "F1@0.01", 3), ("F1@0.02", "F1@0.02", 3),
        ("NC", "NC", 3), ("R_all@0.01", "recall all @0.01", 3), ("R_all@0.02", "recall all @0.02", 3),
        ("out@0.01", "outliers > 0.01 (%)", 2), ("out@0.02", "outliers > 0.02 (%)", 2)]


def surface_distance(points: np.ndarray, gt) -> np.ndarray:
    """Exact unsigned distance from each point to the GT triangle mesh (Open3D RaycastingScene)."""
    import open3d as o3d
    scene = o3d.t.geometry.RaycastingScene()
    scene.add_triangles(o3d.core.Tensor(np.asarray(gt.vertices, np.float32)), o3d.core.Tensor(np.asarray(gt.faces, np.uint32)))
    return scene.compute_distance(o3d.core.Tensor(points.astype(np.float32))).numpy()


def score(shape: str, suffix: str, n: int, seed: int) -> dict:
    run = Path("outputs") / f"{shape}{suffix}"
    pts = load_points_ply(run / "align" / "points_aligned.ply")
    gt = load_mesh(Path("data/scenes") / shape / "gt_normalized.ply")
    idx = np.random.default_rng(seed).choice(len(pts["points"]), n, replace=False)
    p, nrm = pts["points"][idx].astype(np.float64), pts["normals"][idx]
    out = {"run": run.name, "n_source": int(len(pts["points"])), "n": n, "seed": seed, **score_points(p, nrm, gt)}
    centre, scale = unit_cube_transform(gt)
    gt_n = gt.copy()
    gt_n.vertices = (gt.vertices - centre) * scale
    d = surface_distance((p - centre) * scale, gt_n)
    out.update({"out@0.01": float(100 * (d > 0.01).mean()), "out@0.02": float(100 * (d > 0.02).mean()),
                "dist_mean": float(d.mean()), "dist_p95": float(np.percentile(d, 95))})
    (run / "eval").mkdir(parents=True, exist_ok=True)
    (run / "eval" / "equal_count.json").write_text(json.dumps(out, indent=2))
    return out


def fmt(v: np.ndarray, d: int) -> str:
    return f"{v.mean():.{d}f} ± {v.std(ddof=1):.{d}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=1_000_000)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="docs/results/2026-11-17_equal_count.md")
    args = ap.parse_args()
    res = {}
    for s in [DEV] + SET_A + SET_B:
        for _, suf in RUNS:
            res[(s, suf)] = score(s, suf, args.n, args.seed)
            r = res[(s, suf)]
            print(f"[equal] {s}{suf}: {r['n_source']:,} -> {r['n']:,}  CD {r['CD']:.2f}  F1@0.01 {r['F1@0.01']:.3f}  "
                  f"out@0.01 {r['out@0.01']:.1f}%  out@0.02 {r['out@0.02']:.1f}%")
    L = ["# Equal-count comparison: TSDF vs TSDF + gap fill at exactly 1,000,000 points", "",
         "Fahad Qaseem Khawar, 17 Nov 2026. Generated by `scripts/equal_count.py`. Set A = 7 original shapes, set B = 12 "
         "new shapes (clean test set); pencilpot is the dev shape and is in no mean. Mean ± std over shapes.", "",
         f"**Method.** Both clouds are subsampled to exactly {args.n:,} points, uniformly at random without replacement "
         f"(`numpy.random.default_rng({args.seed})`). The TSDF cloud already has exactly 1M points, so for it the draw only reorders "
         "them; the gap-filled cloud (1.01M to 1.33M points) loses its excess at random, so the share of kernel points stays "
         "as in the full cloud. Then protocol v1 (`docs/methods.md` section 9): Chamfer / Hausdorff x100 on 5,000 points, "
         "F1 / NC on 100,000, recall with all points. **Outliers** = share of points whose exact distance to the GT "
         "surface (Open3D `RaycastingScene.compute_distance` on the GT triangles) exceeds 0.01 or 0.02 in the normalised "
         "frame (GT largest extent = 1, so 0.01 = 1% of the object's size). This is 100 minus precision with all points, "
         "measured against the exact surface instead of 100k surface samples.", ""]
    for name, shapes in [("Set B (12 shapes, clean test set)", SET_B), ("Set A (7 shapes)", SET_A)]:
        L += [f"**{name}**", "", "| points | " + " | ".join(c[1] for c in COLS) + " |",
              "|---|" + "---:|" * len(COLS)]
        for label, suf in RUNS:
            L.append(f"| {label} | " + " | ".join(fmt(np.array([res[(s, suf)][k] for s in shapes]), d) for k, _, d in COLS) + " |")
        diffs = []
        for k, lbl, d in COLS:
            dv = np.array([res[(s, "_dfill")][k] - res[(s, "_dense")][k] for s in shapes])
            better = (dv < 0).sum() if k in ("CD", "HD") or k.startswith("out") else (dv > 0).sum()
            diffs.append(f"{lbl} {dv.mean():+.{d}f} (better on {better} of {len(shapes)})")
        L += ["", "Paired per shape, gap fill minus TSDF: " + "; ".join(diffs) + ".", ""]
    L += ["**Per shape** (Chamfer / F1@0.02 / outliers > 0.01 % / outliers > 0.02 %)", "",
          "| shape | gap-fill points before subsampling | TSDF (1M) | TSDF + gap fill (1M) |", "|---|---:|---:|---:|"]
    for s in [DEV] + SET_A + SET_B:
        a, b = res[(s, "_dense")], res[(s, "_dfill")]
        cell = lambda r: f"{r['CD']:.2f} / {r['F1@0.02']:.3f} / {r['out@0.01']:.1f} / {r['out@0.02']:.1f}"
        tag = " (dev)" if s == DEV else " (B)" if s in SET_B else ""
        L.append(f"| {s}{tag} | {b['n_source']:,} | {cell(a)} | {cell(b)} |")
    Path(args.out).write_text("\n".join(L) + "\n")
    print(f"[report] {args.out}")


if __name__ == "__main__":
    main()
