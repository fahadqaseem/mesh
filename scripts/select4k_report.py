"""Regenerate docs/results/2026-11-19_seeded_4k.md (Task D). Everything from "<!-- manual -->" on is kept."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from robustness_report import MANUAL, MESH_COLS, OUT, SET_B, cells, header, line, load, pipe, sd  # noqa: E402

ROWS = [("MeshFlow's own random 4,096 of the TSDF cloud (current)", "_tex_v3"),
        ("random 4,096, numpy seed 0 (ours)", "_k4random"), ("FPS 4,096", "_k4fps"),
        ("curvature-weighted FPS 4,096 (lambda 2)", "_k4wfps"), ("upper bound: clean GT points", "_gtsamples")]


def paired(a: str, b: str, key: str) -> str:
    d = np.array([pipe(s, b)["mesh"][key] - pipe(s, a)["mesh"][key] for s in SET_B if pipe(s, a)["mesh"] and pipe(s, b)["mesh"]])
    if not len(d):
        return "-"
    better = (d < 0).sum() if key in ("CD", "HD", "V") else (d > 0).sum()
    return f"{d.mean():+.3g} ± {sd(d):.2g} ({'fewer' if key == 'V' else 'better'} on {better} of {len(d)})"


def main() -> None:
    out = Path("docs/results/2026-11-19_seeded_4k.md")
    old = out.read_text() if out.exists() else ""
    manual = old[old.index(MANUAL):] if MANUAL in old else f"{MANUAL}\n## Interpretation\n\n(written when the queue has finished)\n"
    n = len(SET_B)
    L = ["# Choosing MeshFlow's 4,096 input points: random (fixed seed), FPS, curvature-weighted FPS", "",
         "Fahad Qaseem Khawar, 19 Nov 2026. Generated by `scripts/select4k_report.py`; interpretation by hand. Set B (12 "
         "shapes, clean test set), MeshFlow seed 42, protocol v1 mesh metrics. Each cloud is exactly 4,096 points chosen "
         "from the dense TSDF cloud (1M, `<s>_dense`) by `scripts/select4k.py`, so MeshFlow's own `randperm` only reorders "
         "them (`docs/methods.md` section 7). The random rule uses numpy `default_rng(0)` for every shape, i.e. the same "
         "selection rule across methods and runs. Curvature-weighted FPS: each step maximises distance x (1 + 2 c / mean c), "
         "c = PCA surface variation over 16 neighbours; lambda = 2 fixed in advance, not tuned.", "",
         "**Set B (12 shapes, clean test set)**", "", header(["MeshFlow input"], MESH_COLS)]
    for label, suf in ROWS:
        L.append(line([label] + cells([pipe(s, suf) for s in SET_B], MESH_COLS, "mesh", n)))
    L += ["", "Paired per shape against our seeded random pick: " + "; ".join(
        f"{lbl}: Chamfer {paired('_k4random', suf, 'CD')}, NC {paired('_k4random', suf, 'NC')}, #V {paired('_k4random', suf, 'V')}"
        for lbl, suf in ROWS[2:4]) + ". Our seeded random vs MeshFlow's own pick: Chamfer "
        f"{paired('_tex_v3', '_k4random', 'CD')}, #V {paired('_tex_v3', '_k4random', 'V')}.", "",
        "**Per shape (Chamfer / NC / #V)**", "", "| shape | " + " | ".join(l.split(' (')[0] for l, _ in ROWS[:4]) + " |",
        "|---|" + "---:|" * 4]
    for s in SET_B:
        items = [f"{m['CD']:.2f} / {m['NC']:.3f} / {m['V']:,}" if (m := pipe(s, suf)["mesh"]) else "" for _, suf in ROWS[:4]]
        L.append(line([s] + items))
    out.write_text("\n".join(L) + "\n\n" + manual)
    print(f"[report] {out}")


if __name__ == "__main__":
    main()
