"""Regenerate docs/results/2026-11-14_gap_fill.md: TSDF points + Gaussian kernels only where the TSDF is missing.

Usage: python scripts/fill_report.py [--out docs/results/2026-11-14_gap_fill.md]
Safe on partial results. Everything from "<!-- manual -->" onwards in the existing doc is kept.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from points_report import COV, NPTS, PCOLS, paired
from robustness_report import DEV, MANUAL, MESH_COLS, OUT, SET_A, SET_B, cells, header, line, load, pipe

RCOLS = [("R_all@0.01", "recall, all points @0.01", 3), ("R_all@0.02", "recall, all points @0.02", 3)]
INPUTS = [("TSDF points (v3, default)", "_tex_v3"), ("Gaussian kernels", "_gsk"),
          ("TSDF + kernels in gaps 3-10% (primary)", "_tfill"), ("TSDF + kernels in gaps 2-5% (secondary)", "_tfill2")]
SETS = [("Set B (12 shapes, clean test set)", SET_B), ("Set A (7 shapes)", SET_A)]
KEYS = ["CD", "HD", "F1@0.01", "F1@0.02", "NC", "R_all@0.02"]


def queue_line() -> str:
    q, st = OUT / "fill_queue" / "queue.tsv", OUT / "fill_queue" / "status.tsv"
    if not q.exists():
        return ""
    total = sum(1 for _ in q.open())
    last = {}
    for r in (ln.rstrip("\n").split("\t") for ln in st.open()) if st.exists() else []:
        if len(r) >= 4:
            last[r[2]] = r[3]
    bad = sorted(k for k, v in last.items() if v != "ok")
    return f"Queue: {sum(v == 'ok' for v in last.values())} of {total} jobs ok" + (f"; not ok: {', '.join(bad)}" if bad else "") + "."


def added(shapes: list[str], suffix: str) -> str:
    a = [f["added"] for s in shapes if (f := load(OUT / f"{s}{suffix}" / "align" / "fill.json"))]
    return f"{np.mean(a):,.0f} ± {np.std(a, ddof=1) if len(a) > 1 else 0:,.0f}" if a else "-"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/results/2026-11-14_gap_fill.md")
    out = Path(ap.parse_args().out)
    old = out.read_text() if out.exists() else ""
    manual = old[old.index(MANUAL):] if MANUAL in old else ""
    L = ["# Gap filling: TSDF points plus Gaussian-kernel points only where the TSDF surface is missing", "",
         "Fahad Qaseem Khawar, 14 Nov 2026. Tables regenerated by `scripts/fill_report.py`; the interpretation at the "
         "end is written by hand. Points scored against the GT with protocol v1 (as in "
         "`docs/results/2026-11-12_points.md`); MeshFlow is the secondary row. Set A = 7 original shapes, set B = 12 "
         "new shapes (clean test set); pencilpot is the dev shape (both rules were chosen on it) and is in no mean.", "",
         queue_line(), "",
         "**Rule** (`scripts/fill_points.py`, `src/photo2mesh/points/fill.py`, no GT used): keep every TSDF point "
         "(200k) and add the Gaussian-kernel samples (`_gsk`, 200k, opacity-weighted) whose distance to the nearest "
         "TSDF point lies in a band, as a fraction of the TSDF cloud's largest extent: far enough to be a gap, close "
         "enough not to be a floater. Primary band 3-10% (best Chamfer on pencilpot), secondary 2-5% (best "
         "recall on pencilpot). A neighbour-count filter against isolated samples made pencilpot worse and is off.", ""]
    L += ["## 1. Points vs GT", ""]
    for name, shapes in SETS:
        n = len(shapes)
        L += [f"**{name}**", "", header(["points"], PCOLS + COV + RCOLS + NPTS)]
        for label, suf in INPUTS:
            runs = [pipe(s, suf) for s in shapes]
            L.append(line([label] + cells(runs, PCOLS, "points", n) + cells(runs, COV, "stats", n) +
                          cells(runs, RCOLS, "points", n) + cells(runs, NPTS, "points", n)))
        L += ["", f"Kernel points added per shape: primary {added(shapes, '_tfill')}, secondary {added(shapes, '_tfill2')}.",
              "", "Paired per shape, minus TSDF: " + "; ".join(
                  f"{lbl.split(' (')[0].replace('TSDF + kernels in gaps ', 'gaps ')}: " +
                  ", ".join(f"{k} {paired(shapes, '_tex_v3', suf, k)}" for k in KEYS)
                  for lbl, suf in INPUTS[2:]) + ".", ""]
    L += ["## 2. MeshFlow on the primary fill (secondary), seed 42", ""]
    for name, shapes in SETS:
        n = len(shapes)
        L += [f"**{name}**", "", header(["MeshFlow input"], MESH_COLS)]
        for label, suf in [INPUTS[0], INPUTS[2], ("upper bound: clean GT points", "_gtsamples")]:
            L.append(line([label] + cells([pipe(s, suf) for s in shapes], MESH_COLS, "mesh", n)))
        L.append("")
    L += ["## 3. Per shape (points Chamfer / F1@0.02 / recall, all points @0.02)", "",
          "| shape | TSDF | gaps 3-10% | gaps 2-5% | added (3-10%) |", "|---|---:|---:|---:|---:|"]
    for s in [DEV] + SET_A + SET_B:
        items = []
        for suf in ["_tex_v3", "_tfill", "_tfill2"]:
            p = pipe(s, suf)["points"]
            items.append(f"{p['CD']:.2f} / {p['F1@0.02']:.3f} / {p['R_all@0.02']:.3f}" if p else "")
        f = load(OUT / f"{s}_tfill" / "align" / "fill.json")
        if items[1]:
            L.append(line([s + (" (dev)" if s == DEV else " (B)" if s in SET_B else "")] + items +
                          [f"{f['added']:,}" if f else ""]))
    L.append("")
    out.write_text("\n".join(L) + "\n" + (manual or f"{MANUAL}\n## Interpretation\n\n(written when the queue has finished)\n"))
    print(f"[report] {out}")


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(Path(__file__).parent))
    main()
