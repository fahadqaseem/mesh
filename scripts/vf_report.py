"""Report: 12 views over three rings, and the GT-free joint fit of depth scale and focal (set B).

Usage: python scripts/vf_report.py [--out docs/results/2026-11-19_views_focal.md]
Inputs: outputs/<s>_{dense,lowB,v16,v12,v12r3}/ (views), outputs/<s>_{ds,jf,vfocal,dsg}/ and
outputs/<s>_ds/points/depth_scale_joint.json (focal fit; scripts/views_focal_run.sh), outputs/pencilpot_299291_* (tuning),
outputs/icp_check/icp_check_B_offset.json (ICP with scale, GT upper bound). Scores via scripts/ds_report.py helpers
(exactly 1M points, protocol v1 + outliers + signed offset; GT gap test against the current 8-view cloud).
Hand-written blocks between <!-- tag --> markers survive a rerun.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from ds_report import O, gap_filled, load, ms, paired, score_new, table  # noqa: E402
from make_points_queue import DEV, SET_B  # noqa: E402


def guard(runs: list[str], name: str = "mem_guard.json") -> str:
    w = [json.loads(p.read_text()) for r in runs for p in [O / r / "points" / name] if p.exists()]
    if not w:
        return "no guard logs"
    lv = {1: "green", 2: "yellow", 4: "red"}
    return (f"{len(w)} guarded VGGT runs, worst pressure {lv.get(max(x['worst_level'] for x in w))}, lowest free "
            f"{min(x['min_free'] for x in w):.0f}%, {sum(x['aborted'] for x in w)} aborted")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/results/2026-11-19_views_focal.md")
    args = ap.parse_args()
    B = SET_B
    L = ["# 12 views over three rings, and a GT-free joint fit of depth scale and focal (set B)", "",
         "Fahad Qaseem Khawar, 19 Nov 2026. Generated by `scripts/vf_report.py`. Set B = 12 new shapes (clean test set); "
         "pencilpot (dev) only for tuning, in no mean. Mean ± std over shapes. Clouds: exactly 1M points ("
         "the TSDF samples 1M points from the fused surface whatever the view count, so the seed-0 draw only reorders them), protocol v1 + outliers (exact distance to the GT triangles); signed offset = "
         "median distance along the GT face normal (> 0 = outside). GT gap = GT surface points farther than 0.02 from the "
         "current 8-view cloud; \"filled\" = now within 0.02. Normalised frame: GT extent 1.", "",
         "<!-- summary -->", "<!-- /summary -->", ""]

    # 1. views
    sets = [("_dense", "current 8 views (4 at 20 + 4 at 50 deg)"), ("_lowB", "low B, 8 views (2 at 50 + 4 at 20 + 2 at -10 deg; 18 Nov)"),
            ("_v12", "12 views, two rings (6 at 20 + 6 at 50 deg; 15 Nov)"),
            ("_v12r3", "**12 views, three rings (4 at 50 + 4 at 20 + 4 at -10 deg)**"), ("_v16", "16 views, two rings (8 + 8; 15 Nov)")]
    sets = [(x, l) for x, l in sets if all((O / f"{s}{x}" / "align" / "points_aligned.ply").exists() for s in B)]
    R = {(s, x): (load(s, x) if x == "_dense" else score_new(s, x)) for s in B for x, _ in sets}
    others = [x for x, _ in sets if x != "_dense"]
    G = {s: gap_filled(s, "_dense", others) for s in B}
    L += ["## 1. 12 views over three rings", "",
          "Rendered rig: `data/scenes_low/<s>` (24 views: 20, 50 and -10 deg rings of 8; the first 16 are pixel-identical to "
          "the usual renders). **12 views, three rings** = ids 0, 2, 4, 6 (20 deg, azimuth 0/90/180/270), 9, 11, 13, 15 "
          "(50 deg, 67.5/157.5/247.5/337.5), 17, 19, 21, 23 (-10 deg, 45/135/225/315), i.e. the current 8 plus four low "
          "views. VGGT on all 12 at once under `scripts/mem_guard.py`; everything else default (known focal, TSDF, 1M points, "
          f"camera alignment). Memory: {guard([f'{s}_v12r3' for s in B])}.", "",
          "| views | Chamfer | F1@0.01 | recall all @0.02 | outliers > 0.01 (%) | outliers > 0.02 (%) | signed offset | GT gap filled (%) |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for x, lbl in sets:
        rs = [R[(s, x)] for s in B]
        gf = "-" if x == "_dense" else ms([G[s][x] for s in B], 1)
        L.append(f"| {lbl} | {ms([r['CD'] for r in rs], 2)} | {ms([r['F1@0.01'] for r in rs], 3)} | "
                 f"{ms([r['R_all@0.02'] for r in rs], 3)} | {ms([r['out@0.01'] for r in rs], 1)} | "
                 f"{ms([r['out@0.02'] for r in rs], 1)} | {ms([r['offset'] for r in rs], 4)} | {gf} |")
    L += ["", f"GT gap of the current 8-view cloud: {ms([G[s]['gap'] for s in B], 1)}% of the surface.", "",
          "Paired per shape against the current 8 views:", ""]
    for x, lbl in sets[1:]:
        L.append(paired([R[(s, '_dense')] for s in B], [R[(s, x)] for s in B], lbl.replace("**", "")))
    L += ["", "**Per shape** (Chamfer / recall all @0.02 / outliers > 0.02 % / gap filled %)", "",
          "| shape | " + " | ".join(l.split(" (")[0].replace("**", "") for _, l in sets) + " |", "|---|" + "---:|" * len(sets)]
    for s in B:
        L.append(f"| {s} | " + " | ".join(
            f"{R[(s, x)]['CD']:.2f} / {R[(s, x)]['R_all@0.02']:.3f} / {R[(s, x)]['out@0.02']:.1f} / " +
            ("-" if x == "_dense" else f"{G[s][x]:.0f}") for x, _ in sets) + " |")
    L += ["", "<!-- interp1 -->", "<!-- /interp1 -->", ""]

    # 2. focal
    pp = DEV
    L += ["## 2. GT-free joint fit of depth scale and focal", "",
          "**Method** (`src/photo2mesh/points/depth_scale.py` `fit_joint`, `scripts/depth_scale.py --joint`). Same multi-view "
          "agreement cost as the 18 Nov depth scale (truncated mean relative depth residual between all ordered view pairs, "
          "bilinear lookup, eps 0.005), now with two parameters for all views: depth scale k and focal factor phi (focal = "
          "phi x the known render focal of 711.6 px; principal point fixed at the centre). The fused pixels are back-projected "
          "with phi f and projected into the other views with phi f; VGGT's camera poses stay fixed. Grid k 0.94-1.08 and "
          "phi 0.88-1.06 (step 0.01), then step 0.0025 around the best. Fused with the default TSDF using both "
          "(`tsdf_points.py --depth-scale --focal-scale`). No GT anywhere in the fit. Unit test: a synthetic sphere given a "
          "focal 1/0.95 too long and depth x 0.97 is recovered to 0.01 (`tests/test_depth_scale.py`). Reference without "
          "a fit: VGGT's own predicted focal with its depth (`intrinsics: predicted`), also GT-free.", "",
          "**Tuning on pencilpot only:**", "",
          "| pencilpot | k | phi | Chamfer | F1@0.01 | recall all @0.02 | outliers > 0.01 (%) | outliers > 0.02 (%) | signed offset |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    cams = np.load(O / f"{pp}_dense" / "points" / "cameras.npz")
    pred_ratio = float(cams["intrinsic_pred"][:, 0, 0].mean() / cams["intrinsic"][:, 0, 0].mean())
    for suf, lbl, k, phi in [("_ds", "default (known focal, no scale)", "1", "1"),
                             ("_ds_global_e0.005", "depth scale only (18 Nov)", "1.0165", "1"),
                             ("_jf_e0.005", "joint fit, eps 0.005 (chosen)", None, None), ("_jf_e0.01", "joint fit, eps 0.01", None, None),
                             ("_vfocal", "VGGT's own focal, no fit", "1", f"{pred_ratio:.3f} (mean)")]:
        r = score_new(pp, suf)
        if k is None:
            e = suf.split("_e")[-1]
            j = json.loads((O / f"{pp}_ds" / "points" / f"depth_scale_joint_e{e}.json").read_text())
            k, phi = f"{j['k']:.4f}", f"{j['phi']:.4f}"
        L.append(f"| {lbl} | {k} | {phi} | {r['CD']:.2f} | {r['F1@0.01']:.3f} | {r['R_all@0.02']:.3f} | {r['out@0.01']:.1f} | "
                 f"{r['out@0.02']:.1f} | {r['offset']:+.4f} |")
    L += ["", "<!-- tune -->", "<!-- /tune -->", ""]
    done = [s for s in B if (O / f"{s}_jf" / "align" / "points_aligned.ply").exists()]
    if done:
        icp = {r["shape"]: r for r in json.loads((O / "icp_check" / "icp_check_B_offset.json").read_text())}
        jf = {s: json.loads((O / f"{s}_ds" / "points" / "depth_scale_joint.json").read_text()) for s in done}
        ratio = {s: float(np.load(O / f"{s}_dense" / "points" / "cameras.npz")["intrinsic_pred"][:, 0, 0].mean() / 711.58)
                 for s in done}
        rows = [("TSDF, current default (known focal)", [load(s, "_dense") for s in done]),
                ("depth scale only (18 Nov)", [load(s, "_dsg") for s in done]),
                ("joint fit: depth scale + focal (GT-free)", [score_new(s, "_jf") for s in done]),
                ("VGGT's own focal, no fit (GT-free)", [score_new(s, "_vfocal") for s in done]),
                ("ICP with scale vs GT (upper bound, NOT protocol v1)",
                 [{**icp[s]["sim3"], "offset": icp[s]["sim3"]["signed_offset"]} for s in done])]
        L += [f"**Set B ({len(done)} shapes)**", ""] + table(rows)
        L += ["", "Paired per shape against the current default:", "",
              paired(rows[0][1], rows[2][1], "joint fit"), paired(rows[0][1], rows[3][1], "VGGT's own focal"), "",
              "**Per shape**: fitted k and phi, VGGT's own focal / known focal, and Chamfer / outliers > 0.02 % / signed offset", "",
              "| shape | k | phi | VGGT focal / known | default | joint fit | VGGT's own focal |", "|---|---:|---:|---:|---:|---:|---:|"]
        cell = lambda r: f"{r['CD']:.2f} / {r['out@0.02']:.1f} / {r['offset']:+.4f}"
        for i, s in enumerate(done):
            L.append(f"| {s} | {jf[s]['k']:.4f} | {jf[s]['phi']:.4f} | {ratio[s]:.3f} | {cell(rows[0][1][i])} | "
                     f"{cell(rows[2][1][i])} | {cell(rows[3][1][i])} |")
        phis = np.array([jf[s]["phi"] for s in done])
        rr = np.array([ratio[s] for s in done])
        L += ["", f"Fitted phi vs VGGT's focal / known focal: mean {phis.mean():.3f} vs {rr.mean():.3f}, mean absolute difference "
              f"{np.abs(phis - rr).mean():.3f}, correlation {np.corrcoef(phis, rr)[0, 1]:.2f}. Memory: "
              f"{guard([f'{s}_ds' for s in done], 'mem_guard_jf.json')}.", "", "<!-- interp2 -->", "<!-- /interp2 -->", ""]

    text = "\n".join(L) + "\n"
    if Path(args.out).exists():
        old = Path(args.out).read_text()
        for tag in ["summary", "interp1", "tune", "interp2"]:
            m = re.search(f"<!-- {tag} -->.*?<!-- /{tag} -->", old, re.S)
            if m:
                text = re.sub(f"<!-- {tag} -->.*?<!-- /{tag} -->", lambda _: m.group(0), text, flags=re.S)
    Path(args.out).write_text(text)
    print(f"[report] {args.out}")


if __name__ == "__main__":
    main()
