"""Report for the 17 Nov follow-ups: alignment check (ICP, diagnostic) and confidence ablation on set B.

Usage: python scripts/conf_report.py [--out docs/results/2026-11-17_conf_ablation.md]
Inputs: outputs/icp_check/icp_check.json (scripts/icp_check.py), outputs/<s>_{c50,c30,c10,c10e0}/ (scripts/conf_ablation.sh),
outputs/<s>_c50/eval/conf_pixels.json (scripts/conf_pixels.py), outputs/<s>_{dense,dfill}/ (15 Nov dense runs).
Cloud scores: scripts/equal_count.py score() (exactly 1M points, seed 0, protocol v1 + exact-distance outliers).
Signed offset: median distance along the GT face normal of 100k points (> 0 = outside the GT surface).
Gap test: GT surface points (100k, protocol sampler) farther than 0.02 from a base cloud are its "gap"; the report gives
the share of them that a variant brings within 0.02 (all points of the variant; normalised frame, GT extent 1).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import open3d as o3d
from scipy.spatial import cKDTree

from photo2mesh.eval.metrics import sample_surface
from photo2mesh.eval.protocol import unit_cube_transform
from photo2mesh.io import load_mesh, load_points_ply

sys.path.insert(0, str(Path(__file__).parent))
from equal_count import score  # noqa: E402
from make_points_queue import SET_A, SET_B  # noqa: E402

CLOUDS = [("_dense", "TSDF, conf 50 (current default, 15 Nov run)"),
          ("_c50", "TSDF, conf 50 (rerun, same VGGT settings)"),
          ("_c30", "TSDF, conf 30"), ("_c10", "TSDF, conf 10"),
          ("_c10e0", "TSDF, conf 10, no 2 px erosion (every VGGT foreground pixel)"),
          ("_dfill", "TSDF conf 50 + gap fill (subsampled to 1M)")]
COLS = [("CD", "Chamfer", 2), ("F1@0.02", "F1@0.02", 3), ("R_all@0.02", "recall all @0.02", 3),
        ("out@0.01", "outliers > 0.01 (%)", 2), ("out@0.02", "outliers > 0.02 (%)", 2)]


def ms(v, d: int) -> str:
    v = np.asarray(v, float)
    return f"{v.mean():.{d}f} ± {v.std(ddof=1):.{d}f}"


def normalised(shape: str):
    gt = load_mesh(Path("data/scenes") / shape / "gt_normalized.ply")
    c, s = unit_cube_transform(gt)
    g = gt.copy()
    g.vertices = (gt.vertices - c) * s
    return gt, g, c, s


def signed_offset(p: np.ndarray, g) -> float:
    scene = o3d.t.geometry.RaycastingScene()
    scene.add_triangles(o3d.core.Tensor(np.asarray(g.vertices, np.float32)), o3d.core.Tensor(np.asarray(g.faces, np.uint32)))
    q = p.astype(np.float32)
    r = scene.compute_closest_points(o3d.core.Tensor(q))
    sd = ((q - r["points"].numpy()) * r["primitive_normals"].numpy()).sum(1)
    return float(np.median(sd[np.abs(sd) < 0.05]))


def cloud(shape: str, suf: str, c, s) -> np.ndarray:
    return (load_points_ply(Path("outputs") / f"{shape}{suf}" / "align" / "points_aligned.ply")["points"] - c) * s


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/results/2026-11-17_conf_ablation.md")
    args = ap.parse_args()
    icp = {r["shape"]: r for r in json.loads(Path("outputs/icp_check/icp_check.json").read_text())}
    shapes = [s for s in SET_B if (Path("outputs") / f"{s}_c50" / "eval" / "conf_pixels.json").exists()]
    pix = {s: json.loads((Path("outputs") / f"{s}_c50" / "eval" / "conf_pixels.json").read_text()) for s in shapes}
    res, gap, off = {}, {}, {}
    for sh in shapes:
        gt, g, c, s = normalised(sh)
        gt_pts = sample_surface(g, 100_000)[0]
        clouds = {suf: cloud(sh, suf, c, s) for suf, _ in CLOUDS}
        for suf, _ in CLOUDS:
            f = Path("outputs") / f"{sh}{suf}" / "eval" / "equal_count.json"
            res[(sh, suf)] = json.loads(f.read_text()) if f.exists() and suf in ("_dense", "_dfill") else score(sh, suf, 1_000_000, 0)
            off[(sh, suf)] = signed_offset(clouds[suf][np.random.default_rng(0).choice(len(clouds[suf]), 100_000, replace=False)], g)
        d = {suf: cKDTree(p).query(gt_pts, distance_upper_bound=0.05)[0] for suf, p in clouds.items()}
        base_of = {"_dfill": "_dense", "_c30": "_c50", "_c10": "_c50", "_c10e0": "_c50", "_dense": "_dense", "_c50": "_c50"}
        for suf in clouds:
            hole = d[base_of[suf]] > 0.02
            gap[(sh, suf)] = (float(100 * hole.mean()), float(100 * (d[suf][hole] <= 0.02).mean()) if hole.any() else 0.0)
        print(f"[report] {sh}: " + "  ".join(f"{suf} CD {res[(sh, suf)]['CD']:.2f} out2 {res[(sh, suf)]['out@0.02']:.1f} "
                                            f"gapfilled {gap[(sh, suf)][1]:.0f}%" for suf, _ in CLOUDS), flush=True)
    json.dump({f"{k[0]}{k[1]}": {"scores": res[k], "gap": gap[k], "signed_offset": off[k]} for k in res},
              open("outputs/conf_ablation/summary.json", "w"), indent=2)

    n = len(shapes)
    L = ["# Alignment check and confidence ablation (set B)", "",
         f"Fahad Qaseem Khawar, 17 Nov 2026. Generated by `scripts/conf_report.py` from `scripts/icp_check.py`, "
         f"`scripts/conf_ablation.sh` and `scripts/conf_pixels.py`. Set B = {n} new shapes (clean test set). Mean ± std over "
         "shapes. Normalised frame: GT largest extent = 1, so 0.01 = 1% of the object's size.", "",
         "<!-- summary -->", "<!-- /summary -->", ""]

    # 1. alignment
    L += ["## 1. Alignment check: ICP refinement (diagnostic only, NOT protocol v1)", "",
          "The protocol v1 TSDF cloud (`<s>_dense`, 1M points, Umeyama on camera centres) is refined with trimmed "
          "point-to-point ICP against 100k GT surface samples (`photo2mesh.eval.align.icp_sim3`, trim 0.9, 50k-point "
          "subsample, seed 0), once rigid (rotation + translation) and once with scale, then rescored on all points. ICP "
          "uses the GT, so it is never a pipeline step: whatever it removes is alignment error.", ""]
    for name, ss in [("Set B (12 shapes)", SET_B), ("Set A (7 shapes)", SET_A)]:
        L += [f"**{name}**", "", "| alignment | Chamfer | F1@0.01 | F1@0.02 | outliers > 0.01 (%) | outliers > 0.02 (%) |",
              "|---|---:|---:|---:|---:|---:|"]
        for mode, lbl in [("camera", "cameras only (protocol v1)"), ("rigid", "+ rigid ICP"), ("sim3", "+ ICP with scale")]:
            L.append(f"| {lbl} | " + " | ".join(ms([icp[s][mode][k] for s in ss], dd) for k, dd in
                                                 [("CD", 2), ("F1@0.01", 3), ("F1@0.02", 3), ("out@0.01", 2), ("out@0.02", 2)]) + " |")
        L += ["", f"ICP correction: rigid rotation {ms([icp[s]['rigid']['step_rot_deg'] for s in ss], 2)} deg, translation "
              f"{ms([icp[s]['rigid']['step_trans'] for s in ss], 4)}; scale fitted by ICP {ms([icp[s]['sim3']['step_scale'] for s in ss], 3)} "
              f"(below 1 on {sum(icp[s]['sim3']['step_scale'] < 1 for s in ss)} of {len(ss)} shapes).", ""]
    L += ["**Per shape, set B** (outliers > 0.02 %, cameras / rigid / with scale; ICP scale; median signed offset of the "
          "camera-aligned points along the GT normal, > 0 = outside)", "",
          "| shape | out > 0.02: cameras | rigid ICP | ICP with scale | ICP scale | signed offset |", "|---|---:|---:|---:|---:|---:|"]
    for s in SET_B:
        r = icp[s]
        so = f"{off[(s, '_dense')]:+.4f}" if (s, "_dense") in off else "-"
        L.append(f"| {s} | {r['camera']['out@0.02']:.1f} | {r['rigid']['out@0.02']:.1f} | {r['sim3']['out@0.02']:.1f} | "
                 f"{r['sim3']['step_scale']:.3f} | {so} |")
    L += ["", "<!-- interp1 -->", "<!-- /interp1 -->", ""]

    # 2. pixels
    L += ["## 2. Confidence ablation: which pixels each setting fuses", "",
          "Same VGGT output per shape (rerun with the default 8 views and settings, `raw.npz` kept until scored, then "
          "deleted). Variants change only the pixel filter before TSDF fusion (`src/photo2mesh/points/filter.py:75-95`); "
          "everything else default, 1M points. Pixel accuracy: every fused pixel back-projected (known focal), moved by "
          "the run's camera alignment, exact distance to the GT surface.", "",
          "| variant | fused pixels (% of VGGT foreground) | pixels > 0.02 off (%) | median signed offset of pixels | pixels added vs conf 50 | added pixels > 0.02 off (%) |",
          "|---|---:|---:|---:|---:|---:|"]
    vlabel = {"c50": "conf 50 (default)", "c30": "conf 30", "c10": "conf 10", "c10e0": "conf 10, no erosion"}
    for v, lbl in vlabel.items():
        fr = [100 * pix[s]["variants"][v]["fused_over_fg"] for s in shapes]
        o2 = [pix[s]["variants"][v]["all"]["out@0.02"] for s in shapes]
        na = [pix[s]["variants"][v]["added_vs_c50"]["n"] for s in shapes]
        ao = [pix[s]["variants"][v]["added_vs_c50"]["out@0.02"] for s in shapes if pix[s]["variants"][v]["added_vs_c50"]["n"]]
        sg = [pix[s]["variants"][v]["all"]["median_signed"] for s in shapes]
        acell = ms(ao, 1) if len(ao) > 1 else f"{ao[0]:.1f} (1 shape)" if ao else "-"
        L.append(f"| {lbl} | {ms(fr, 1)} | {ms(o2, 1)} | {ms(sg, 4)} | {np.mean(na):,.0f} (non-zero on {sum(x > 0 for x in na)} of {n}) | {acell} |")
    L += ["", "| shape | VGGT foreground (% of image) | conf 50th / 30th / 10th percentile over all pixels | fused pixels: conf 50 / 30 / 10 / 10 no erosion |",
          "|---|---:|---|---|"]
    for s in shapes:
        p = pix[s]
        L.append(f"| {s} | {100 * p['fg_frac']:.1f} | {p['conf_p50_all']:.3f} / {p['conf_p30_all']:.3f} / {p['conf_p10_all']:.3f} | "
                 + " / ".join(f"{p['variants'][v]['fused_pixels']:,}" for v in vlabel) + " |")
    L += ["", "<!-- interp2 -->", "<!-- /interp2 -->", ""]

    # 3. clouds
    L += ["## 3. Confidence ablation: the point clouds (exactly 1M points each, protocol v1 + outliers)", "",
          "| points | " + " | ".join(c[1] for c in COLS) + " | signed offset | GT gap filled (%) |", "|---|" + "---:|" * (len(COLS) + 2)]
    for suf, lbl in CLOUDS:
        L.append(f"| {lbl} | " + " | ".join(ms([res[(s, suf)][k] for s in shapes], d) for k, _, d in COLS) +
                 f" | {ms([off[(s, suf)] for s in shapes], 4)} | " +
                 ("-" if suf in ("_dense", "_c50") else ms([gap[(s, suf)][1] for s in shapes], 1)) + " |")
    L += ["", f"GT gap = GT surface points farther than 0.02 from the conf 50 cloud the variant is built from "
          f"({ms([gap[(s, '_c50')][0] for s in shapes], 1)}% of the surface for the rerun, "
          f"{ms([gap[(s, '_dense')][0] for s in shapes], 1)}% for the 15 Nov cloud); \"filled\" = now within 0.02 of a point.", ""]
    L += ["Paired per shape against the rerun conf 50 cloud (gap fill against the 15 Nov conf 50 cloud):", ""]
    for suf, lbl in CLOUDS[2:]:
        base = "_dense" if suf == "_dfill" else "_c50"
        parts = []
        for k, l, d in COLS:
            dv = np.array([res[(s, suf)][k] - res[(s, base)][k] for s in shapes])
            better = (dv < 0).sum() if k == "CD" or k.startswith("out") else (dv > 0).sum()
            parts.append(f"{l} {dv.mean():+.{d}f} (better on {better} of {n})")
        L.append(f"- {lbl}: " + "; ".join(parts) + ".")
    L += ["", "**Per shape** (Chamfer / recall all @0.02 / outliers > 0.02 %)", "",
          "| shape | " + " | ".join(lbl.split(" (")[0] if suf != "_dense" else "conf 50 (15 Nov)" for suf, lbl in CLOUDS) + " |",
          "|---|" + "---:|" * len(CLOUDS)]
    for s in shapes:
        L.append(f"| {s} | " + " | ".join(f"{res[(s, suf)]['CD']:.2f} / {res[(s, suf)]['R_all@0.02']:.3f} / "
                                          f"{res[(s, suf)]['out@0.02']:.1f}" for suf, _ in CLOUDS) + " |")
    L += ["", "<!-- interp3 -->", "<!-- /interp3 -->", ""]
    text = "\n".join(L) + "\n"
    if Path(args.out).exists():                          # keep hand-written blocks between the markers
        import re
        old = Path(args.out).read_text()
        for tag in ["summary", "interp1", "interp2", "interp3"]:
            m = re.search(f"<!-- {tag} -->.*?<!-- /{tag} -->", old, re.S)
            if m:
                text = re.sub(f"<!-- {tag} -->.*?<!-- /{tag} -->", lambda _: m.group(0), text, flags=re.S)
    Path(args.out).write_text(text)
    print(f"[report] {args.out}")


if __name__ == "__main__":
    main()
